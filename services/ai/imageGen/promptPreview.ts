/**
 * 提示词装配预览。
 *
 * 不派生自上游任何函数——上游没有对应能力。这里存在的理由是**可验证性**：
 * 移植过程中最容易出错的三个环节是角色 `$…$` 替换、替换规则、以及尺寸剥离，
 * 而它们的效果只有发一次请求、看服务端返回的图片才能确认。
 * 本模块把 `组装单图提示词` 的每一步中间结果摊开，让这些环节在本地就能核对。
 *
 * 修改声明（AFPL v9 §2(c)(i)）：本文件为新增，非上游代码的改写；
 * 但它复用的 `组装单图提示词` 派生自 st-chatu8 的 `extractImagePrompt3` 家族
 * （L16641-L16674）与提示词组装段，因此整体仍受本仓库的 AFPL 声明约束。
 */

import type { 文生图系统设置 } from '@/models/genSystem';
import type { 角色匹配上下文 } from './characterPrompt';
import { 组装单图提示词, 取提示词预设 } from './generateIllustration';
import { 取出提示词正文, 默认插图标记, 剥出尺寸 } from './illustrationProtocol';
import { 处理角色提示词, 提取出场角色 } from './characterPrompt';
import { 应用替换规则 } from './promptRules';

export interface 提示词预览 {
  /** 原始输入（含标记外壳）。 */
  原始输入: string;
  /** 剥掉 `image###…###` 外壳后的正文。 */
  提示词正文: string;
  /** `$…$` 角色替换后的文本。 */
  角色替换后: string;
  /** 替换规则应用后的主体提示词。 */
  主体提示词: string;
  /** 最终正向提示词。 */
  正向提示词: string;
  /** 最终负向提示词。 */
  负向提示词: string;
  /** 命中的角色（名称 + 位置）. */
  命中角色: Array<{ 名称: string; 提示词: string; 位置: string }>;
  /**
   * 本轮会填进 ComfyUI 工作流 LoRA 槽位的角色 LoRA（最多 4 个）。
   *
   * 它是「角色绑定 → 实际生效」这条链上唯一能提前看见的环节：
   * 槽位只在角色**出场**时才有值，没命中就是空数组（对应的 LoraLoader 会被跳过）。
   */
  lora: Array<{ 名称: string; 权重: number }>;
  /** 角色带出的负面词。 */
  角色负面: string;
  /** 从提示词里剥出的尺寸；未写或未开启自主分辨率时为 null。 */
  宽度: number | null;
  高度: number | null;
  /** 自主分辨率开关状态，用于解释尺寸为什么没被剥出。 */
  自主分辨率: boolean;
  预设名称: string;
  /** 装配过程中产生的错误；出错时其余字段为尽力而为的结果。 */
  错误?: string;
}

/** 复现装配的每一步。纯函数，不发请求。 */
export function 生成提示词预览(
  设置: 文生图系统设置,
  输入: string,
  角色上下文: 角色匹配上下文,
): 提示词预览 {
  const 原始输入 = 输入 ?? '';
  const 空结果: 提示词预览 = {
    原始输入,
    提示词正文: '',
    角色替换后: '',
    主体提示词: '',
    正向提示词: '',
    负向提示词: '',
    命中角色: [],
    lora: [],
    角色负面: '',
    宽度: null,
    高度: null,
    自主分辨率: 设置.comfyui.自主分辨率,
    预设名称: '',
  };

  try {
    const { 名称: 预设名称, 预设 } = 取提示词预设(设置);
    const 正文 = 取出提示词正文(原始输入, 默认插图标记);
    // 与 组装单图提示词 同序：先剥尺寸，再角色替换，再替换规则。
    const 剥尺寸 = 剥出尺寸(正文, 设置.comfyui.自主分辨率);
    const 角色替换 = 处理角色提示词(剥尺寸.提示词, 角色上下文);
    const 规则集 = 设置.提示词.替换规则列表[设置.提示词.当前替换规则];
    const 替换 = 应用替换规则(角色替换.提示词, 规则集?.规则文本 ?? '');
    const 出场 = 提取出场角色(剥尺寸.提示词, 角色上下文);

    const 组装 = 组装单图提示词(设置, 原始输入, 角色上下文);

    return {
      ...空结果,
      lora: 组装.lora ?? [],
      提示词正文: 正文,
      角色替换后: 角色替换.提示词,
      主体提示词: 替换.modifiedPrompt,
      正向提示词: 组装.正向提示词,
      负向提示词: 组装.负向提示词,
      命中角色: 出场.map((项) => ({
        名称: 项.角色.nameCN || 项.角色.nameEN || 项.角色.id,
        提示词: 项.提示词,
        位置: 项.位置 ? `${项.位置.x}, ${项.位置.y}` : '未指定',
      })),
      角色负面: 角色替换.角色负面,
      宽度: 组装.宽度,
      高度: 组装.高度,
      预设名称,
      // 预设存在性由 组装单图提示词 检查，这里提前暴露，避免预览静默为空。
      错误: 预设 ? undefined : `找不到提示词预设「${预设名称}」。`,
    };
  } catch (错误) {
    return {
      ...空结果,
      错误: 错误 instanceof Error ? 错误.message : String(错误),
    };
  }
}
